"""The server runs the world; clients show it (M1/M3).

- Native's simple triggers and triggers run only on the campaign server (and in single player). A campaign
  client runs them too (seen 2026-11-07: simple trigger 97 -> calculate_castle_prosperities_by_using_its_villages,
  division by zero on every frame), on a local copy of the world that game_start never set up. The guard
  "server or not a campaign" goes in front of every native entry; our own triggers are added later, unguarded.
- Until encounters with player parties exist (M3), AI parties do not pick a player party as a target. The engine
  asks game_check_party_sees_party(looker, target) (mapped script 0x1d, called only by
  mbParty::aiCollectPossibleTargets; trigger result preset to 1 = seen). Without this, bandits that reached a
  player's party started a simulated battle with it again and again (native game_event_simulate_battle) and the
  player could not move. DEVIATION from native, temporary.
- A joining client sees native's main party (the training field) until the server tells it its own party: a
  "Joining the campaign" screen covers that (closes when the party is known, or after 15 seconds).
"""
from header_common import *
from header_operations import *
from header_presentations import *
from header_triggers import *
from module_constants import *
import fcpatch as fp

# continue only on the campaign server or outside a campaign (single player)
SERVER_OR_SINGLE_PLAYER = [
    (this_or_next | multiplayer_is_server),
    (neg | multiplayer_is_campaign),
]


def _guard_simple_trigger(entry):
    # (interval, ops)
    return (entry[0], SERVER_OR_SINGLE_PLAYER + list(entry[1])) + tuple(entry[2:])


def _guard_trigger(entry):
    # (check interval, delay interval, rearm interval, conditions, consequences)
    return tuple(entry[:3]) + (SERVER_OR_SINGLE_PLAYER + list(entry[3]),) + tuple(entry[4:])


scripts = [
    # Engine: does party 1 see party 2 (for its AI targets)? Trigger result 0 = no.
    ("game_check_party_sees_party", [
        (store_script_param, ":fc_looker", 1),
        (store_script_param, ":fc_target", 2),
        (store_add, ":fc_end", "p_fc_player_party_0", fc_max_players),
        (try_begin),
            (multiplayer_is_campaign),
            (is_between, ":fc_target", "p_fc_player_party_0", ":fc_end"),
            (neg | is_between, ":fc_looker", "p_fc_player_party_0", ":fc_end"),
            (set_trigger_result, 0),
        (try_end),
    ]),
]

def _presentations(native):
    from ID_meshes import mesh_loading_background   # generated by the build; only there by the time presentations are
    return [
    ("fc_joining", prsntf_read_only, mesh_loading_background, [
        (ti_on_presentation_load, [
            (set_fixed_point_multiplier, 1000),
            (str_store_string, s1, "@Joining the campaign..."),
            (create_text_overlay, reg1, s1, tf_center_justify),
            (position_set_x, pos1, 500),
            (position_set_y, pos1, 340),
            (overlay_set_position, reg1, pos1),
            (position_set_x, pos1, 2000),
            (position_set_y, pos1, 2000),
            (overlay_set_size, reg1, pos1),
            (presentation_set_duration, 999999),
        ]),
        (ti_on_presentation_run, [
            (store_trigger_param_1, ":fc_ms"),
            (try_begin),
                (this_or_next | gt, "$fc_my_party", 0),
                (gt, ":fc_ms", 15000),
                (presentation_set_duration, 0),
            (try_end),
        ]),
    ]),
    ]

simple_triggers = [
    # campaign client, once: cover the map until our party is known
    (0, [
        (multiplayer_is_campaign),
        (neg | multiplayer_is_server),
        (eq, "$fc_my_party", 0),
        (eq, "$fc_joining_shown", 0),
        (assign, "$fc_joining_shown", 1),
        (start_presentation, "prsnt_fc_joining"),
    ]),
]

patches = [
    # first, so they see only native's entries
    fp.edit_all("simple_triggers", _guard_simple_trigger, origin="fc_authority"),
    fp.edit_all("triggers", _guard_trigger, origin="fc_authority"),
    fp.add("scripts", scripts, origin="fc_authority"),
    fp.add_from("presentations", _presentations, origin="fc_authority"),
    fp.add("simple_triggers", simple_triggers, origin="fc_authority"),
]
